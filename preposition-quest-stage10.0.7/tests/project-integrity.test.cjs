const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const js = fs.readFileSync(path.join(root, 'js', 'game.js'), 'utf8');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m => m[1]);
assert.equal(ids.length, new Set(ids).size, 'HTML IDs must be unique');
for (const id of ['quizScreen','answerChoiceList','typingAnswerForm','typingAnswerInput','speakingChallenge','startSpeakingBtn','switchToTypingBtn','sentenceBuilder','sentenceSlots','sentenceWordBank','submitSentenceBtn','continueQuizBtn']) assert.ok(ids.includes(id), `Missing #${id}`);
assert.match(html, /js\/quiz-manager\.js/);
assert.match(html, /js\/game\.js/);
const dataStart = js.indexOf('const challengeData = [');
assert.ok(dataStart >= 0, 'challenge data exists');
const dataEnd = js.indexOf('];', dataStart);
const data = js.slice(dataStart, dataEnd);
assert.equal((data.match(/id:"challenge-\d+"/g)||[]).length, 8, 'exactly eight challenges');
for (const mode of ['multiple-choice','picture-sentence','drag-drop','typing','speaking']) assert.ok(data.includes(`mode:"${mode}"`), `mode ${mode} is represented`);
assert.ok(data.includes('mode:"picture-sentence"'), 'picture-to-sentence challenge is present');
assert.ok(data.includes('The backpack is behind the tree.'), 'accepted sentence is present');
for (const f of ['over.svg','under.svg','through.svg','around.svg','next-to.svg','between.svg','behind.svg','in-front-of.svg']) assert.ok(fs.existsSync(path.join(root,'assets','clues',f)), `Missing clue ${f}`);
for (const f of ['sfx_gem.ogg','sfx_select.ogg','sfx_coin.ogg','sfx_hurt.ogg','sfx_jump-high.ogg','sfx_disappear.ogg','sfx_jump.ogg','sfx_throw.ogg','sfx_magic.ogg','sfx_bump.ogg']) assert.ok(fs.existsSync(path.join(root,'assets','audio',f)), `Missing audio ${f}`);
console.log('PASS: Project integrity checks');
